/* Четверть арочного кольца (радиусы 60/32, пружинная линия y=90, центр 80,90).
   Дуга начинается не от замка, а в 0,20 рад от него: этот зазор занимает
   замковый камень. Без зазора арка смыкалась сама собой, замок ложился сверху
   декоративной шапочкой, и форма противоречила собственному определению. */
function archQuarter(dir) {
  const cx = 80, cy = 90, ro = 60, ri = 32, gap = 0.20;
  const outer = [], inner = [];
  for (let i = 0; i <= 9; i++) {
    const t = gap + (Math.PI / 2 - gap) * (i / 9);
    const s = Math.sin(t), c = Math.cos(t);
    outer.push([cx + dir * ro * s, cy - ro * c]);
    inner.push([cx + dir * ri * s, cy - ri * c]);
  }
  return outer.concat(inner.reverse());
}

AG.archQuarter = archQuarter;

// зона, которой принадлежит станция сборки
AG.zoneOfElement = function (elIdx) {
  return AG.CONTENT.zones.findIndex(z => z.els.indexOf(elIdx) >= 0);
};
