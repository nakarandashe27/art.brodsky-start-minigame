// Четверть арочного кольца (радиусы 60/32, пружинная линия y=90, центр 80,90)
function archQuarter(dir) {
  const cx = 80, cy = 90, ro = 60, ri = 32;
  const outer = [], inner = [];
  for (let i = 0; i <= 9; i++) {
    const t = (Math.PI / 2) * (i / 9); // 0..PI/2 — четверть кольца
    const s = Math.sin(t), c = Math.cos(t);
    outer.push([cx + dir * ro * s, cy - ro * c]);
    inner.push([cx + dir * ri * s, cy - ri * c]);
  }
  return outer.concat(inner.reverse());
}

AG.archQuarter = archQuarter;
